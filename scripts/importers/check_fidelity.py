#!/usr/bin/env python3
"""
Content-fidelity check: prove a conversion changed markup and nothing else.

PLAN.md makes content fidelity non-negotiable -- ported prose must survive the port intact.
This compares the *word multiset* of an upstream source against its converted page and reports
anything dropped. Word-level rather than line-level, because the converter legitimately reflows
wrapped list items and re-indents code, but must never lose a word.

    python scripts/importers/check_fidelity.py <source.md.txt> <converted.md>
    python scripts/importers/check_fidelity.py --manifest  # every page in sources.toml

Expected drops are metadata the converter is meant to strip (Colab badges, "View on
ai.google.dev", `<br>`). Those are filtered by EXPECTED_DROPS; anything else is a finding.

Exit codes: 0 = faithful, 1 = prose lost, 2 = usage error.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DOCS_DIR = REPO_ROOT / "docs"
MANIFEST = Path(__file__).resolve().parent / "sources.toml"

# Markup tokens that legitimately change form during conversion:
#   NOTE/WARNING/...  `> [!NOTE]` becomes `!!! Note` (different case, so it reads as a drop)
#   ---               table separators are regenerated by fix_tables
EXPECTED_DROPS = {"NOTE", "IMPORTANT", "WARNING", "TIP", "CAUTION", "---"}

WORD = re.compile(r"[A-Za-z0-9_.+-]{2,}")
BASE64_PAYLOAD = re.compile(r"data:image/[A-Za-z0-9.+-]+;base64,[A-Za-z0-9+/=\s]+")
NOTEBOOK_PREAMBLE = re.compile(r"^This notebook will run on\b", re.IGNORECASE)

# Image *locations* legitimately change during the port -- base64 payloads become files
# (port_docs.py) and hotlinks become local paths (vendor_images.py). Only the alt text is prose,
# so the target is blanked on both sides before comparing. Without this, vendoring an image
# reads as six dropped words and would block the page from ever being re-ported.
MD_IMAGE_TARGET = re.compile(r"(!\[[^\]]*\]\()[^)]*(\))")
HTML_IMAGE_TARGET = re.compile(r"(<img[^>]+src=[\"'])[^\"']*([\"'])")

# Link targets that Step 0.5 rewrites on purpose: an upstream docs URL in the source becomes a
# local .md path in the output. Both forms are blanked so the retargeting doesn't read as loss.
# Deliberately narrow -- other external links (Hugging Face, Kaggle, GitHub) stay in the
# comparison, so silently losing one of those is still caught.
# `[Video](youtube-url)` becomes an <iframe> embed, so the URL changes form. Both the original
# link target and the embed src are blanked; the visible text is unaffected either way.
YOUTUBE_URL = re.compile(
    r"https?://(?:www\.)?(?:youtube(?:-nocookie)?\.com|youtu\.be)/\S*"
)
IFRAME_SRC = re.compile(r"(<iframe[^>]+src=[\"'])[^\"']*([\"'])")

# `[](url)` -- a link with no visible text. Devsite card grids emit one alongside a titled link
# to the same URL; collapsing the card drops the empty duplicate. No prose is involved.
EMPTY_LINK = re.compile(r"\[\]\([^)]*\)")

REWRITTEN_LINK_TARGET = re.compile(
    r"(\]\()"
    r"(?:https?://ai\.google\.dev/gemma/docs[^)\s]*"
    r"|[^)\s]*\.md(?:#[^)\s]*)?"
    r")"
    r"(\))"
)


def strip_designed_drops(source_text: str) -> str:
    """Remove the lines convert_notebook is *designed* to discard.

    Comparing raw source against output would flag every Colab/Kaggle badge as lost prose. The
    honest comparison is "source minus the chrome we deliberately strip" vs. the output, so this
    reuses the converter's own predicate rather than maintaining a parallel word blocklist --
    the two can't drift apart.
    """
    from convert_notebook import is_badge_line

    lines = source_text.splitlines()
    kept = []
    for i, line in enumerate(lines):
        stripped = line.strip()
        if is_badge_line(line) or NOTEBOOK_PREAMBLE.match(stripped):
            continue
        if stripped in ("<br />", "<br/>", "<br>"):
            continue
        if stripped.startswith("|---"):
            previous = lines[i - 1].strip() if i > 0 else ""
            following = lines[i + 1].strip() if i + 1 < len(lines) else ""
            if is_badge_line(previous) or is_badge_line(following):
                continue
        kept.append(line)
    return "\n".join(kept)


def normalise(token: str) -> str:
    """Trim edge punctuation so a word doesn't change identity by moving in a sentence.

    WORD keeps `.`/`-`/`+`/`_` so tokens like `ai.google.dev` and `v1.1` survive intact, but that
    also glues on trailing punctuation: `[CodeGemma](url).` tokenises as `CodeGemma` (the `]`
    stops it) while the delinked `CodeGemma.` tokenises with the period. Same word, different
    token, reported as loss.
    """
    return token.strip("._-+")


def words(text: str) -> Counter:
    """Word multiset, ignoring image targets and base64 payloads (see the regexes above)."""
    text = BASE64_PAYLOAD.sub(" ", text)
    text = MD_IMAGE_TARGET.sub(r"\1\2", text)
    text = HTML_IMAGE_TARGET.sub(r"\1\2", text)
    text = REWRITTEN_LINK_TARGET.sub(r"\1\2", text)
    text = EMPTY_LINK.sub("", text)
    text = IFRAME_SRC.sub(r"\1\2", text)
    text = YOUTUBE_URL.sub("", text)
    tokens = (normalise(t) for t in WORD.findall(text))
    return Counter(t for t in tokens if len(t) >= 2)


def strip_frontmatter(text: str) -> str:
    """Drop the YAML block. It is metadata this repo adds (PLAN.md Step 3.1), never prose
    from upstream, so counting it would report every page as having gained words."""
    if not text.startswith("---"):
        return text
    lines = text.split("\n")
    for idx in range(1, len(lines)):
        if lines[idx].strip() == "---":
            return "\n".join(lines[idx + 1 :])
    return text


def compare(source_text: str, converted_text: str) -> tuple[Counter, Counter]:
    """Return (unexpected drops, additions)."""
    source = words(strip_designed_drops(source_text))
    converted = words(strip_frontmatter(converted_text))
    dropped = Counter({w: c for w, c in (source - converted).items() if w not in EXPECTED_DROPS})
    return dropped, converted - source


def report(label: str, dropped: Counter, added: Counter, verbose: bool = False) -> bool:
    """Print one page's result. Returns True if faithful."""
    if not dropped:
        detail = f"  (+{sum(added.values())} markup words)" if verbose else ""
        print(f"  OK    {label}{detail}")
        return True
    print(f"  LOST  {label} -- {sum(dropped.values())} word(s) dropped:")
    for word, count in dropped.most_common(15):
        print(f"          {word!r} x{count}")
    if len(dropped) > 15:
        print(f"          ... and {len(dropped) - 15} more")
    return False


def cache_name(page_path: str) -> str:
    """Cache filename for a manifest page. Shared with port_docs.py -- keep the two identical."""
    return page_path.replace("/", "_") + ".txt"


def fetch(source: str) -> str:
    if source.startswith(("http://", "https://")):
        import urllib.request
        req = urllib.request.Request(source, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req) as resp:
            return resp.read().decode("utf-8")
    return Path(source).read_text(encoding="utf-8")


def check_manifest(cache_dir: Path | None, verbose: bool) -> int:
    pages = tomllib.loads(MANIFEST.read_text(encoding="utf-8"))["page"]
    print(f"Checking {len(pages)} page(s) against upstream\n")
    failures = frozen = 0
    for entry in pages:
        target = DOCS_DIR / entry["path"]
        if entry.get("frozen"):
            # Hand-maintained: divergence from upstream is intended, not a defect.
            print(f"  FROZEN {entry['path']}")
            frozen += 1
            continue
        if not target.exists():
            print(f"  SKIP  {entry['path']} (not yet ported)")
            continue
        # Must match port_docs.py's scheme: many pages are named index.md, so keying the
        # cache on the bare filename collides them all onto one entry.
        cached = cache_dir / cache_name(entry["path"]) if cache_dir else None
        if cached and cached.exists():
            source_text = cached.read_text(encoding="utf-8")
        else:
            source_text = fetch(entry["source"])
            if cached:
                cached.parent.mkdir(parents=True, exist_ok=True)
                cached.write_text(source_text, encoding="utf-8")
        dropped, added = compare(source_text, target.read_text(encoding="utf-8"))
        if not report(entry["path"], dropped, added, verbose):
            failures += 1
    checked = len(pages) - frozen
    print(f"\n{checked - failures} faithful, {failures} with dropped prose, {frozen} frozen")
    return 1 if failures else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", nargs="?", help="upstream .md.txt path or URL")
    parser.add_argument("converted", nargs="?", help="converted .md path")
    parser.add_argument("--manifest", action="store_true", help="check every page in sources.toml")
    parser.add_argument("--cache-dir", default=None, help="cache fetched sources here")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    if args.manifest:
        return check_manifest(Path(args.cache_dir) if args.cache_dir else None, args.verbose)

    if not (args.source and args.converted):
        parser.error("provide <source> and <converted>, or use --manifest")

    dropped, added = compare(fetch(args.source), Path(args.converted).read_text(encoding="utf-8"))
    return 0 if report(Path(args.converted).name, dropped, added, verbose=True) else 1


if __name__ == "__main__":
    sys.exit(main())
